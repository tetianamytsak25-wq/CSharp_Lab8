        public Glyph8x10 GetGlyph(char symbol)
        {
            char key = char.ToUpperInvariant(symbol);
            Glyph8x10 glyph = new Glyph8x10();

            if (!font.TryGetValue(key, out string[]? pattern))
            {
                return glyph;
            }

            for (int y = 0; y < pattern.Length; y++)
            {
                for (int x = 0; x < pattern[y].Length; x++)
                {
                    if (pattern[y][x] == '1')
                    {
                        glyph.SetPixel(x + 1, y + 1, true);
                    }
                }
            }
            return glyph;
        }
